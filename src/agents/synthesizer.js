/**
 * Synthesizer agent: combines several files into one new Markdown document.
 *
 * ── IN SIMPLE WORDS ──
 * You pick a few files (say, three meeting notes) and a format, and this
 * writes a single new document out of them: a unified requirements doc, a
 * combined summary, or a side-by-side comparison. Every line that comes from
 * a file says which file, and the document ends with a numbered Sources list.
 *
 * ── BUSINESS RULES ──
 * - Spec "Synthesizer agent": FORMATS = requirements ("Unified Requirements"),
 *   summary ("Summary"), compare ("Comparison"); the title is the format name.
 * - Every output ends with "## Sources" listing the input files 1..n, in the
 *   order given — the "with citations" judging requirement relies on it.
 * - Offline requirements doc: Overview, Requirements, Decisions, Action Items
 *   ("- [ ] <item> (<file>)"), Key Figures. Summary: Overview, Key Points,
 *   Decisions, Key Figures. Compare: a table with one row per file, Common
 *   Themes, Key Figures.
 * - With an AI key, the AI writes the document from the files (each capped at
 *   12,000 chars); if its reply has no "## Sources", one is appended.
 * - Every result carries a one-line `summary` (max 160 chars) that the
 *   server stores as the file's summary: requirements "Unified requirements
 *   from <a, b and c> (N files): R requirements, D decisions, A action
 *   items."; summary "Summary of … (N files): <first key point>"; compare
 *   "Comparison of … (N files); common themes: x, y, z."; the AI path
 *   "<lead> … (N files)." File names lose their extension and any shared
 *   word prefix ("q3-marketing-"); past 4 files only the count is named
 *   (tested in synthesizer.test and server.test).
 *
 * ── WHY IT'S BUILT THIS WAY (change at your peril) ──
 * - The offline path is pure rule-based extraction from src/text.js, so the
 *   feature works with no key and its output is deterministic and testable.
 * - Any AI failure (throw, empty reply) falls back to the offline document
 *   and logs once (test: "falls back on error"), so a quota error never
 *   loses the user's request.
 * - Per-file truncation keeps the prompt bounded when big files are combined.
 * - The summary is built here, from the same lists that fill the document,
 *   and passed to saveGenerated(). Without it the file was summarised from
 *   its own first sentence, the "Generated by the Synthesizer agent…" line,
 *   so every synthesized file read the same.
 *
 * ── DO NOT ──
 * - Do not drop the Sources section (on either path) — the judges' "with
 *   citations" requirement relies on it.
 * - Do not strip the "(<file name>)" tags from extracted lines; they are the
 *   per-line citations.
 */
import { summarize, splitSentences, tokenize, extractDecisions, extractRequirements, extractActionItems, extractAmounts, topTerms } from '../text.js';

export const FORMATS = { requirements: 'Unified Requirements', summary: 'Summary', compare: 'Comparison' };
const MAX_CHARS_PER_DOC = 12000;

const bullets = (items) => (items.length ? items.map((i) => `- ${i}`).join('\n') : '- None found.');
const sourcesSection = (docs) => `## Sources\n${docs.map((d, i) => `${i + 1}. ${d.name}`).join('\n')}`;
const tagged = (docs, fn) => docs.flatMap((d) => fn(d.text).map((x) => `${x} (${d.name})`));
const today = () => new Date().toISOString().slice(0, 10);

const LEADS = { requirements: 'Unified requirements from', summary: 'Summary of', compare: 'Comparison of' };
const plural = (n, word) => `${n} ${word}${n === 1 ? '' : 's'}`;
const listOf = (xs) => (xs.length <= 1 ? xs.join('') : `${xs.slice(0, -1).join(', ')} and ${xs[xs.length - 1]}`);
const clip = (s, max = 160) => (s.length > max ? `${s.slice(0, max - 1).trimEnd()}…` : s);

// "q3-marketing-kickoff.md", "q3-marketing-wrapup.md" -> "kickoff", "wrapup": the shared prefix tells them apart from nothing.
function fileLabels(docs) {
  const parts = docs.map((d) => d.name.replace(/\.[^.]+$/, '').split(/[-_\s]+/).filter(Boolean));
  let k = 0;
  while (parts.length > 1 && parts.every((p) => p.length > k + 1 && p[k].toLowerCase() === parts[0][k].toLowerCase())) k++;
  return parts.map((p) => p.slice(k).join(' '));
}

// "Unified requirements from kickoff and review (2 files)"; past 4 files the names would not fit.
const sourcesPhrase = (docs, format) => `${LEADS[format]} ${docs.length <= 4 ? `${listOf(fileLabels(docs))} (${docs.length} files)` : `${docs.length} files`}`;

function keySentences(text, n) {
  const freq = new Map();
  for (const t of tokenize(text)) freq.set(t, (freq.get(t) || 0) + 1);
  return splitSentences(text.replace(/^#+.*$/gm, ''))
    .filter((s) => s.split(/\s+/).length >= 6)
    .map((s, i) => ({ s, i, score: tokenize(s).reduce((a, t) => a + (freq.get(t) || 0), 0) / Math.sqrt(tokenize(s).length || 1) }))
    .sort((a, b) => b.score - a.score)
    .slice(0, n)
    .sort((a, b) => a.i - b.i)
    .map((x) => x.s.replace(/^[-*]\s*(\[[ x]\]\s*)?/i, ''));
}

export function synthesizeOffline(docs, format) {
  const title = FORMATS[format];
  const header = `# ${title}\n\n_Generated by the Synthesizer agent from ${docs.length} files on ${today()} (offline mode)._`;
  const overview = `## Overview\n${docs.map((d) => `- **${d.name}**: ${summarize(d.text)}`).join('\n')}`;
  const figures = `## Key Figures\n${bullets(tagged(docs, extractAmounts))}`;
  // Owner lines ("Sara will …") match the decision pattern too; they belong under Action Items only.
  const actionSet = new Set(docs.flatMap((d) => extractActionItems(d.text)));
  const decisionList = docs.flatMap((d) => extractDecisions(d.text).filter((s) => !actionSet.has(s)).map((s) => `${s} (${d.name})`));
  const decisions = `## Decisions\n${bullets(decisionList)}`;
  let body;
  let summary;
  const who = sourcesPhrase(docs, format);
  if (format === 'requirements') {
    const actions = tagged(docs, extractActionItems);
    const requirements = tagged(docs, extractRequirements);
    body = [overview, `## Requirements\n${bullets(requirements)}`, decisions,
      `## Action Items\n${actions.length ? actions.map((a) => `- [ ] ${a}`).join('\n') : '- None found.'}`, figures];
    summary = `${who}: ${plural(requirements.length, 'requirement')}, ${plural(decisionList.length, 'decision')}, ${plural(actions.length, 'action item')}.`;
  } else if (format === 'summary') {
    const points = docs.flatMap((d) => keySentences(d.text, 2));
    body = [overview, `## Key Points\n${bullets(docs.flatMap((d) => keySentences(d.text, 2).map((s) => `${s} (${d.name})`)))}`, decisions, figures];
    summary = `${who}: ${points[0] ?? summarize(docs[0].text)}`;
  } else {
    const termSets = docs.map((d) => new Set(topTerms(d.text, 15)));
    const common = [...termSets[0]].filter((t) => termSets.every((s) => s.has(t)));
    const rows = docs.map((d, i) => `| ${d.name} | ${summarize(d.text, 90).replace(/\|/g, '/')} | ${extractAmounts(d.text).slice(0, 3).join(', ') || '-'} | ${extractDecisions(d.text).length} | ${[...termSets[i]].filter((t) => !common.includes(t)).slice(0, 4).join(', ') || '-'} |`);
    body = [`## Side by Side\n| File | Summary | Key figures | Decisions | Unique topics |\n| --- | --- | --- | --- | --- |\n${rows.join('\n')}`,
      `## Common Themes\n${bullets(common.slice(0, 8))}`, figures];
    summary = common.length ? `${who}; common themes: ${common.slice(0, 3).join(', ')}.` : `${who}.`;
  }
  return { title, content: [header, ...body, sourcesSection(docs)].join('\n\n') + '\n', summary: clip(summary) };
}

const INSTRUCTIONS = {
  requirements: 'Write a unified project requirements document: Overview, Requirements, Decisions, Open Questions, Action Items (as "- [ ]" checkboxes with owners and dates).',
  summary: 'Write a concise combined summary: Overview, Key Points, Decisions, Key Figures.',
  compare: 'Compare the files: a Markdown table (one row per file), then Common Themes, Differences and Conflicts.',
};

export async function synthesize(docs, format, { llm, log = () => {} } = {}) {
  if (!llm?.enabled()) return { ...synthesizeOffline(docs, format), by: 'offline' };
  const files = docs.map((d) => {
    const cut = d.text.length > MAX_CHARS_PER_DOC;
    return `=== File: ${d.name}${cut ? ' (truncated)' : ''} ===\n${d.text.slice(0, MAX_CHARS_PER_DOC)}`;
  }).join('\n\n');
  const prompt = `${INSTRUCTIONS[format]}\nUse only facts from the files. Write Markdown starting with "# ${FORMATS[format]}". Mention which file each fact comes from.\n\n${files}`;
  try {
    let content = (await llm.complete(prompt, { system: 'You combine documents into clear, accurate new documents.' }))?.trim();
    if (!content) throw new Error('AI returned an empty document');
    if (!/## Sources/.test(content)) content += `\n\n${sourcesSection(docs)}`;
    // The AI's document has no counts we can trust, so its summary names the format and the sources.
    return { title: FORMATS[format], content: `${content}\n`, summary: clip(`${sourcesPhrase(docs, format)}.`), by: 'ai' };
  } catch (err) {
    log('Synthesizer', `AI unavailable (${err.message}); built the document with offline rules instead.`);
    return { ...synthesizeOffline(docs, format), by: 'offline' };
  }
}
